'use client'

import { useState } from 'react'
import { HYGIENE_LOCATIONS, DAY_LABELS, shortLocation } from '@/lib/constants'
import { CellSelect, CellInput, locationTone } from './cells'
import DateInput from './DateInput'
import TimeRangeField from './TimeRangeField'

// ─────────────────────────────────────────────────────────────────────────────
// LAYOUT CONTRACT — read this before changing any width.
//
// Same contract as ACHTable and ZeroPaymentsTable: `table-layout: fixed` with a
// <colgroup> built from these numbers, so cell content can never change column
// geometry and every row lines up in every state.
//
// THE TOTAL MUST FIT THE CONTAINER. app/hygiene/page.js puts `px-6` OUTSIDE the
// `max-w-[1600px]` box — the same structure as the hero, so every card on the
// page shares one set of edges — which leaves 1552px usable. (1600 rather than
// 1280 because seven location tabs, including "Dentique Downers Grove", cramp
// at the narrower width.)
// Exceed it and the table grows a horizontal scrollbar and clips Actions.
//
//   1165 columns + 90 actions = 1255, leaving 25px of slack.
//   Actions is 90 because the word "ACTIONS" itself needs ~56px at
//   text-[11px] tracking-widest — 70 squeezed the header.
//   Location is 200 so "Dentique Downers Grove" fits without truncating.
//
// Day and % are READ-ONLY: both are generated by the database from the other
// fields. Rendering them as inert text rather than dead inputs makes it obvious
// they fill themselves.
// ─────────────────────────────────────────────────────────────────────────────
const COLS = [
  { key: 'location',  label: 'Location',  width: 200 },
  { key: 'workDate',  label: 'Date',      width: 145 },
  { key: 'dayNum',    label: 'Day',       width: 100 },
  { key: 'hours',     label: 'Hours',     width: 170 },
  { key: 'available', label: 'Available', width: 100 },
  { key: 'utilized',  label: 'Utilized',  width: 100 },
  { key: 'pct',       label: '%',         width: 155 },
  { key: 'notes',     label: 'Notes',     width: 195 },
]
const ACTIONS_WIDTH = 90

// Figures are right-aligned so a column of them can be compared digit by digit.
const NUMERIC_COLS = new Set(['available', 'utilized'])

const LOCATION_OPTIONS = HYGIENE_LOCATIONS.map((l) => ({ value: l, label: shortLocation(l) }))

// Utilization bands. Green is "at or near capacity", amber is "slipping",
// red is "materially under-booked" — the whole point of tracking this.
export function pctTone(pct) {
  if (pct == null) return 'bg-slate-100 text-slate-400 border-slate-200'
  if (pct >= 90)   return 'bg-emerald-100 text-emerald-700 border-emerald-200'
  if (pct >= 75)   return 'bg-amber-100 text-amber-700 border-amber-200'
  return 'bg-red-100 text-red-700 border-red-200'
}

function barColor(pct) {
  if (pct == null) return 'bg-slate-300'
  if (pct >= 90)   return 'bg-emerald-500'
  if (pct >= 75)   return 'bg-amber-500'
  return 'bg-red-500'
}

export default function HygieneTable({
  rows, loading, sortConfig, onSort,
  onSaveFields, onDelete,
  canEdit = true, canDelete = true,
  onAdd, onImport,
}) {
  const [confirmId, setConfirmId] = useState(null)

  async function commit(row, field, value) {
    if (String(row[field] ?? '') === String(value ?? '')) return
    try { await onSaveFields?.(row, { [field]: value }) }
    catch { alert('Failed to save. Check your connection.') }
  }

  if (loading) {
    return (
      <div className="glass-card rounded-2xl flex items-center justify-center py-16">
        <div className="w-5 h-5 border-2 border-violet-400/40 border-t-violet-500 rounded-full animate-spin" />
      </div>
    )
  }

  // An empty state is an invitation to act, not a dead end. Rather than a tall
  // blank card with a centred shrug, this keeps the height tight and puts the
  // two ways in — one row, or a whole month — directly in reach.
  if (rows.length === 0) {
    return (
      <div className="glass-card rounded-2xl px-6 py-8">
        <div className="flex flex-col sm:flex-row sm:items-center gap-5">
          <div className="w-11 h-11 rounded-xl bg-teal-50 border border-teal-200 flex items-center justify-center shrink-0">
            <svg className="w-5 h-5 text-teal-600" fill="none" stroke="currentColor" strokeWidth="1.75" viewBox="0 0 24 24">
              <path d="M3 17l5-6 4 4 3-4 6 6" strokeLinecap="round" strokeLinejoin="round" />
              <path d="M3 21h18" strokeLinecap="round" />
            </svg>
          </div>

          <div className="flex-1 min-w-0">
            <p className="text-sm font-semibold text-slate-800">No hygiene days here yet</p>
            <p className="text-xs text-slate-500 mt-0.5 leading-relaxed">
              Log a day's available and utilized hours and the utilization percentage works itself out.
              Importing a month at a time is usually faster than entering days one by one.
            </p>
          </div>

          {(onAdd || onImport) && (
            <div className="flex gap-2 shrink-0">
              {onImport && (
                <button
                  onClick={onImport}
                  className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-slate-700 bg-white hover:bg-slate-50 border border-slate-200 rounded-lg transition-all"
                >
                  <svg className="w-3.5 h-3.5" fill="none" stroke="currentColor" strokeWidth="2" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" d="M3 16.5v2.25A2.25 2.25 0 0 0 5.25 21h13.5A2.25 2.25 0 0 0 21 18.75V16.5M16.5 12 12 16.5m0 0L7.5 12m4.5 4.5V3" /></svg>
                  Import a month
                </button>
              )}
              {onAdd && (
                <button
                  onClick={onAdd}
                  className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-white bg-indigo-600 hover:bg-indigo-700 rounded-lg transition-all"
                >
                  <svg className="w-3.5 h-3.5" fill="none" stroke="currentColor" strokeWidth="2" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" d="M12 4.5v15m7.5-7.5h-15" /></svg>
                  Add a day
                </button>
              )}
            </div>
          )}
        </div>
      </div>
    )
  }

  const sortIcon = (key) => {
    if (sortConfig?.key !== key) return null
    return <span className="text-indigo-500 ml-1">{sortConfig.dir === 'asc' ? '↑' : '↓'}</span>
  }

  return (
    <>
      <div className="glass-card rounded-2xl overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full" style={{ tableLayout: 'fixed' }}>
            <colgroup>
              {COLS.map((c) => <col key={c.key} style={{ width: c.width }} />)}
              <col style={{ width: ACTIONS_WIDTH }} />
            </colgroup>
            <thead>
              <tr className="border-b border-slate-200">
                {COLS.map((c) => (
                  <th
                    key={c.key}
                    onClick={() => onSort?.(c.key)}
                    className={`px-4 py-3 text-[11px] font-semibold uppercase tracking-widest text-slate-500 bg-slate-50 cursor-pointer select-none hover:text-slate-700 ${NUMERIC_COLS.has(c.key) ? 'text-right' : 'text-left'}`}
                  >
                    {c.label}{sortIcon(c.key)}
                  </th>
                ))}
                <th className="px-3 py-3 text-center text-[11px] font-semibold uppercase tracking-widest text-slate-500 bg-slate-50">Actions</th>
              </tr>
            </thead>
            <tbody>
              {rows.map((r) => (
                <tr key={r.id} className="border-b border-slate-100 last:border-0 hover:bg-indigo-50/30 transition-colors group/row">
                  <td className="px-4 py-3">
                    <CellSelect
                      value={r.location || ''}
                      options={LOCATION_OPTIONS}
                      onChange={(v) => commit(r, 'location', v)}
                      tone={locationTone(r.location)}
                      disabled={!canEdit}
                      title="Location"
                    />
                  </td>

                  <td className="px-4 py-3">
                    {canEdit ? (
                      <DateInput value={r.workDate || ''} onChange={(iso) => commit(r, 'workDate', iso)} title="Date" />
                    ) : (
                      <span className="text-slate-700 font-medium tabular-nums text-xs">{r.workDate}</span>
                    )}
                  </td>

                  {/* Generated from the date — shown, never entered. */}
                  <td className="px-4 py-3 whitespace-nowrap">
                    <span className="text-xs text-slate-500" title="Derived from the date">
                      {DAY_LABELS[r.dayNum] || '—'}
                    </span>
                  </td>

                  <td className="px-4 py-3">
                    <TimeRangeField
                      value={r.hours || ''}
                      onChange={(v) => commit(r, 'hours', v)}
                      disabled={!canEdit}
                      title="Shift hours"
                    />
                  </td>

                  <td className="px-4 py-3">
                    <CellInput
                      value={r.available ?? ''}
                      onCommit={(v) => commit(r, 'available', v)}
                      placeholder="0"
                      disabled={!canEdit}
                      title="Available hours"
                      align="right"
                    />
                  </td>

                  <td className="px-4 py-3">
                    <CellInput
                      value={r.utilized ?? ''}
                      onCommit={(v) => commit(r, 'utilized', v)}
                      placeholder="0"
                      disabled={!canEdit}
                      title="Utilized hours"
                      align="right"
                    />
                  </td>

                  {/* Generated: utilized / available. A bar alongside the number
                      makes a row of percentages scannable at a glance. */}
                  <td className="px-4 py-3">
                    <div className="flex items-center gap-2">
                      <span className={`badge text-[10px] border tabular-nums ${pctTone(r.pct)}`}>
                        {r.pct != null ? `${r.pct.toFixed(1)}%` : '—'}
                      </span>
                      <div className="flex-1 h-1.5 rounded-full bg-slate-100 overflow-hidden min-w-[28px]">
                        <div
                          className={`h-full rounded-full transition-all ${barColor(r.pct)}`}
                          style={{ width: `${Math.min(100, Math.max(0, r.pct ?? 0))}%` }}
                        />
                      </div>
                    </div>
                  </td>

                  <td className="px-4 py-3">
                    <CellInput
                      value={r.notes || ''}
                      onCommit={(v) => commit(r, 'notes', v)}
                      placeholder="Add notes…"
                      multiline
                      disabled={!canEdit}
                      title="Notes"
                    />
                  </td>

                  <td className="px-3 py-3">
                    {/* A single action does not need a menu — one icon, one click.
                        The confirm dialog is what makes it deliberate. Centred,
                        because one icon left-aligned under a centred header
                        reads as stranded rather than placed. */}
                    <div className="flex justify-center">
                    {canDelete && (
                      <button
                        onClick={() => setConfirmId(r.id)}
                        title="Delete entry"
                        className="p-1.5 rounded-lg text-slate-400 hover:text-red-600 hover:bg-red-50 transition-colors"
                      >
                        <svg className="w-3.5 h-3.5" fill="none" stroke="currentColor" strokeWidth="2" viewBox="0 0 24 24">
                          <path strokeLinecap="round" strokeLinejoin="round" d="m14.74 9-.346 9m-4.788 0L9.26 9m9.968-3.21c.342.052.682.107 1.022.166m-1.022-.165L18.16 19.673a2.25 2.25 0 0 1-2.244 2.077H8.084a2.25 2.25 0 0 1-2.244-2.077L4.772 5.79m14.456 0a48.108 48.108 0 0 0-3.478-.397m-12 .562c.34-.059.68-.114 1.022-.165m0 0a48.11 48.11 0 0 1 3.478-.397m7.5 0v-.916c0-1.18-.91-2.164-2.09-2.201a51.964 51.964 0 0 0-3.32 0c-1.18.037-2.09 1.022-2.09 2.201v.916m7.5 0a48.667 48.667 0 0 0-7.5 0" />
                        </svg>
                      </button>
                    )}
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>

      {confirmId && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4">
          <div className="absolute inset-0 bg-black/60 backdrop-blur-sm" onClick={() => setConfirmId(null)} />
          <div className="relative bg-white border border-slate-200 rounded-2xl shadow-2xl w-full max-w-sm z-10 p-6">
            <h3 className="text-sm font-semibold text-slate-900">Delete this entry?</h3>
            <p className="text-xs text-slate-500 mt-1.5">This removes the day's hygiene record. It cannot be undone.</p>
            <div className="flex justify-end gap-2 mt-5">
              <button onClick={() => setConfirmId(null)} className="px-3 py-1.5 text-sm text-slate-600 hover:text-slate-900 border border-slate-200 rounded-lg">Cancel</button>
              <button onClick={() => { onDelete(confirmId); setConfirmId(null) }} className="btn-danger text-sm py-1.5">Delete</button>
            </div>
          </div>
        </div>
      )}
    </>
  )
}
